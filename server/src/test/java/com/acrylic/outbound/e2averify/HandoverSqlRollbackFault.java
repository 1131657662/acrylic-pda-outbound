package com.acrylic.outbound.e2averify;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.SQLException;
import org.springframework.jdbc.core.JdbcTemplate;
import static org.assertj.core.api.Assertions.assertThat;

/** Isolated-schema AFTER INSERT probe; never overrides a Spring bean or an existing database guard. */
final class HandoverSqlRollbackFault implements AutoCloseable {
    static final String MESSAGE = "E2A_HANDOVER_AFTER_AUDIT_WRITES_VERIFIED";
    private static final String NAME = "e2a_handover_after_audit_abort";
    private final JdbcTemplate jdbc;

    HandoverSqlRollbackFault(JdbcTemplate jdbc, HandoverRollbackFixture fixture, Path attempt) throws Exception {
        this.jdbc = jdbc;
        String sql = definition(fixture);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM information_schema.TRIGGERS "
            + "WHERE TRIGGER_SCHEMA=DATABASE() AND TRIGGER_NAME=?", Integer.class, NAME)).isZero();
        Files.writeString(attempt.resolve("rollback-fault-trigger.sql"), sql);
        jdbc.execute(sql);
    }

    static SQLException requireExpectedFailure(Throwable failure) {
        assertThat(failure).as("the armed audit INSERT must fail").isNotNull();
        Throwable cause = failure;
        while (cause != null && !(cause instanceof SQLException)) cause = cause.getCause();
        assertThat(cause).as("fault must be the exact SQL signal, not another refusal").isInstanceOf(SQLException.class);
        var sql = (SQLException) cause;
        assertThat(sql.getSQLState()).isEqualTo("45000");
        assertThat(sql.getErrorCode()).isEqualTo(1644);
        assertThat(sql.getMessage()).isEqualTo(MESSAGE);
        return sql;
    }

    @Override public void close() { jdbc.execute("DROP TRIGGER " + NAME); }

    private static String definition(HandoverRollbackFixture f) {
        // Every substituted identifier is a UUID generated by the fixture, never arbitrary SQL input.
        return """
            CREATE TRIGGER e2a_handover_after_audit_abort AFTER INSERT ON operation_event FOR EACH ROW
            BEGIN
              IF NEW.event_type='HANDOVER_ACTIVATE'
                AND JSON_UNQUOTE(JSON_EXTRACT(NEW.details,'$.caseId'))='%1$s' THEN
                IF (SELECT status FROM handover_case WHERE id=UUID_TO_BIN('%1$s'))='ACTIVATED'
                  AND (SELECT COUNT(*) FROM order_assignment WHERE order_id=UUID_TO_BIN('%2$s') AND status='ACTIVE')=1
                  AND (SELECT COUNT(*) FROM order_assignment WHERE id=UUID_TO_BIN('%3$s') AND status='REVOKED')=1
                  AND (SELECT work_round FROM submission_scope WHERE id=UUID_TO_BIN('%4$s'))=2
                  AND (SELECT work_round FROM order_submission_slot WHERE order_id=UUID_TO_BIN('%2$s'))=2
                  AND (SELECT COUNT(*) FROM order_sync_outbox WHERE order_id=UUID_TO_BIN('%2$s')
                    AND event_type='HANDOVER_ACTIVATED' AND published_seq IS NULL)=1
                  AND (SELECT COUNT(*) FROM handover_command_receipt WHERE case_id=UUID_TO_BIN('%1$s')
                    AND id=NEW.entity_id AND command_type='ACTIVATE')=1
                  AND (SELECT COUNT(*) FROM bale_commitment WHERE submission_id=UUID_TO_BIN('%5$s'))=1 THEN
                  SIGNAL SQLSTATE '45000' SET MYSQL_ERRNO=1644, MESSAGE_TEXT='E2A_HANDOVER_AFTER_AUDIT_WRITES_VERIFIED';
                ELSE
                  SIGNAL SQLSTATE '45000' SET MYSQL_ERRNO=1644, MESSAGE_TEXT='E2A_HANDOVER_AFTER_AUDIT_STATE_MISMATCH';
                END IF;
              END IF;
            END
            """.formatted(f.caseId, f.order, f.assignment, f.scope, f.submission);
    }
}
