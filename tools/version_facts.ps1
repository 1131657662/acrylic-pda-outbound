<#
.SYNOPSIS
  Generate or verify the "version facts" block so one fact is never hand-copied into several documents.

.DESCRIPTION
  Sources (read-only, single authority):
    Android version   defaults of pdaVersionCode / pdaVersionName in android/app/build.gradle.kts
    Android Room      version = N in android/.../data/PdaDatabase.kt
    Server migrations highest and total count of V*__*.sql in server/src/main/resources/db/migration
    Server contract   info.version and path count of contracts/openapi.yaml
    Git/worktrees     HEAD, branch, uncommitted entry count, worktree count

  Output goes between the FACTS_START / FACTS_END markers of docs/ORCHESTRATION_STATUS.md.
  Default prints only; -Write updates the document; -Check exits 1 on drift or when the board's
  current-state section exceeds its hard caps.

  Works on Windows PowerShell 5.1 and PowerShell 7. ASCII-only on purpose: PowerShell 5.1 reads
  BOM-less scripts with the ANSI code page, which would corrupt non-ASCII string literals.
#>
[CmdletBinding()]
param(
    [string]$RepoRoot,
    [string]$StatusDocument = 'docs/ORCHESTRATION_STATUS.md',
    [switch]$Write,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
# $PSScriptRoot is not yet bound inside the param block under "powershell -File", so resolve it here.
if (-not $RepoRoot) {
    $scriptDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
    $RepoRoot = (Resolve-Path (Join-Path $scriptDirectory '..')).Path
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
# Hard caps for the current-state section: both line count and character count must pass.
$MaxCurrentStateLines = 100
$MaxCurrentStateChars = 8000

function Read-Text([string]$path) { return [System.IO.File]::ReadAllText($path) }
function Write-Text([string]$path, [string]$text) { [System.IO.File]::WriteAllText($path, $text, $utf8) }
function Get-Match([string]$text, [string]$pattern, [string]$what) {
    $match = [regex]::Match($text, $pattern)
    if (-not $match.Success) { throw "Cannot parse $what from source (pattern: $pattern)" }
    return $match.Groups[1].Value
}

$gradle = Read-Text (Join-Path $RepoRoot 'android/app/build.gradle.kts')
$androidCode = Get-Match $gradle 'pdaVersionCode"\)\.map\(String::toInt\)\.orElse\((\d+)\)' 'Android versionCode'
$androidName = Get-Match $gradle 'pdaVersionName"\)\.orElse\("([^"]+)"\)' 'Android versionName'

$database = Read-Text (Join-Path $RepoRoot 'android/app/src/main/java/com/acrylic/outbound/pda/data/PdaDatabase.kt')
$roomVersion = Get-Match $database 'version\s*=\s*(\d+)' 'Room version'

$migrations = @(Get-ChildItem (Join-Path $RepoRoot 'server/src/main/resources/db/migration') -Filter 'V*__*.sql')
$migrationNumbers = @($migrations | ForEach-Object { if ($_.Name -match '^V(\d+)__') { [int]$Matches[1] } } | Sort-Object)
if ($migrationNumbers.Count -eq 0) { throw 'No Flyway migration found' }
$flywayMax = $migrationNumbers[-1]

$openapi = Read-Text (Join-Path $RepoRoot 'contracts/openapi.yaml')
$contractVersion = Get-Match $openapi '(?m)^\s{2}version:\s*(\S+)\s*$' 'contract version'
$contractPaths = ([regex]::Matches($openapi, '(?m)^\s{2}/')).Count

$branch = (& git -C $RepoRoot rev-parse --abbrev-ref HEAD).Trim()
$head = (& git -C $RepoRoot rev-parse --short HEAD).Trim()
$dirty = @(& git -C $RepoRoot status --porcelain).Count
$worktrees = @(& git -C $RepoRoot worktree list --porcelain | Where-Object { $_ -like 'worktree *' }).Count

$generated = @(
    '<!-- FACTS_START -->',
    '<!-- Generated by tools/version_facts.ps1; do not edit by hand. Verify with: powershell -NoProfile -File tools/version_facts.ps1 -Check -->',
    '```yaml',
    "date: $(Get-Date -Format 'yyyy-MM-dd')",
    "branch: $branch",
    "head: $head",
    "dirty_entries: $dirty",
    "worktrees: $worktrees",
    "android: { name: $androidName, code: $androidCode, room: $roomVersion }",
    "server: { contract: $contractVersion, paths: $contractPaths, flyway: V$flywayMax, migrations: $($migrationNumbers.Count) }",
    '```',
    '<!-- FACTS_END -->'
) -join "`n"

$statusPath = Join-Path $RepoRoot $StatusDocument
if (-not (Test-Path $statusPath)) { throw "Status document not found: $StatusDocument" }
$status = Read-Text $statusPath

$factPattern = '(?s)<!-- FACTS_START -->.*?<!-- FACTS_END -->'
$existingFacts = [regex]::Match($status, $factPattern)
# Only the code-derived facts are drift-checked: git state (date/head/dirty_entries/worktrees) changes
# on every commit and would otherwise make -Check fail during normal work.
function Get-StableFacts([string]$block) {
    return (($block -split "`n" | Where-Object { $_ -notmatch '^(date|head|dirty_entries|worktrees):' }) -join "`n")
}
$factsDrift = (-not $existingFacts.Success) -or ((Get-StableFacts $existingFacts.Value) -ne (Get-StableFacts $generated))

$currentPattern = '(?s)<!-- CURRENT_STATE_START -->(.*?)<!-- CURRENT_STATE_END -->'
$currentMatch = [regex]::Match($status, $currentPattern)
if (-not $currentMatch.Success) { throw 'Status document has no CURRENT_STATE_START/END section' }
$currentBody = $currentMatch.Groups[1].Value
$currentLines = ($currentBody -split "`n").Count
$currentChars = $currentBody.Length
$capExceeded = ($currentLines -gt $MaxCurrentStateLines) -or ($currentChars -gt $MaxCurrentStateChars)

if ($Write) {
    if (-not $existingFacts.Success) { throw 'Status document has no FACTS_START/END markers to replace' }
    $evaluator = [System.Text.RegularExpressions.MatchEvaluator] { param($match) $generated }
    Write-Text $statusPath ([regex]::Replace($status, $factPattern, $evaluator))
    Write-Host "Updated facts block in $StatusDocument"
} else {
    Write-Output $generated
}

$problems = @()
if ($Check) {
    if ($factsDrift) { $problems += 'Code-derived facts differ from sources (run: powershell -NoProfile -File tools/version_facts.ps1 -Write)' }
    if ($capExceeded) {
        $problems += "Current-state section exceeds caps: $currentLines lines / $currentChars chars (max $MaxCurrentStateLines lines, $MaxCurrentStateChars chars)"
    }
}
if ($problems.Count -gt 0) {
    $problems | ForEach-Object { Write-Host "FAIL: $_" -ForegroundColor Red }
    exit 1
}
if ($Check) {
    Write-Host "OK: facts block matches sources; current-state section is $currentLines lines / $currentChars chars" -ForegroundColor Green
}
